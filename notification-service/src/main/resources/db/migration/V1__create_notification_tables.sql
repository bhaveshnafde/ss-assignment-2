-- Notification service database. Owned by this service only. Transfer and account IDs from other
-- services are stored as plain values, never as foreign keys to another service's database.

CREATE TABLE notifications (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id         VARCHAR(64)  NOT NULL,
    template            VARCHAR(40)  NOT NULL,
    account_id          VARCHAR(64)  NOT NULL,
    channel             VARCHAR(10)  NOT NULL,
    message             VARCHAR(500) NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    attempts            INTEGER      NOT NULL,
    last_error          VARCHAR(300),
    provider_message_id VARCHAR(40),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at             TIMESTAMP WITH TIME ZONE,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    version             BIGINT       NOT NULL,
    CONSTRAINT chk_notifications_channel CHECK (channel IN ('SMS', 'EMAIL')),
    CONSTRAINT chk_notifications_status CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT chk_notifications_attempts CHECK (attempts >= 0),
    CONSTRAINT chk_notifications_sent CHECK ((status = 'SENT') = (sent_at IS NOT NULL)),
    -- N1: one message per transfer and template. This is what makes "notify" safe to repeat:
    -- a second request for the same transfer finds this row instead of creating another.
    CONSTRAINT uq_notifications_transfer_template UNIQUE (transfer_id, template)
);

CREATE INDEX idx_notifications_account ON notifications (account_id, id);

-- Every call to the (simulated) provider, kept as evidence: failures are recorded, not lost (N3).
CREATE TABLE notification_attempts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT       NOT NULL REFERENCES notifications (id),
    attempt_no      INTEGER      NOT NULL,
    outcome         VARCHAR(10)  NOT NULL,
    error           VARCHAR(300),
    duration_ms     BIGINT       NOT NULL,
    attempted_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_attempts_outcome CHECK (outcome IN ('SENT', 'FAILED')),
    CONSTRAINT uq_attempts_no UNIQUE (notification_id, attempt_no)
);
