-- Ledger service database. Owned by this service only. Account and transfer IDs from other
-- services are stored as plain values, never as foreign keys to another service's database.
--
-- The ledger is APPEND-ONLY: rows are inserted, never updated or deleted. A mistake (or a saga
-- undo) is corrected by inserting a REVERSAL journal with the directions swapped.

CREATE TABLE journals (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id         VARCHAR(64)  NOT NULL,
    type                VARCHAR(20)  NOT NULL,
    currency            VARCHAR(3)   NOT NULL,
    -- set only on a REVERSAL: the journal it cancels
    reverses_journal_id BIGINT       REFERENCES journals (id),
    posted_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_journals_type CHECK (type IN ('TRANSFER', 'REVERSAL')),
    CONSTRAINT chk_journals_reversal_link CHECK (
        (type = 'TRANSFER' AND reverses_journal_id IS NULL) OR
        (type = 'REVERSAL' AND reverses_journal_id IS NOT NULL)),
    -- BR5: one journal per transfer, and at most one reversal of it. This constraint is also
    -- what makes "post journal" safe to repeat, even for two identical requests at once.
    CONSTRAINT uq_journals_transfer_type UNIQUE (transfer_id, type),
    CONSTRAINT uq_journals_reverses UNIQUE (reverses_journal_id)
);

CREATE TABLE journal_entries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id BIGINT         NOT NULL REFERENCES journals (id),
    line_no    INTEGER        NOT NULL,
    account_id VARCHAR(64)    NOT NULL,
    direction  VARCHAR(10)    NOT NULL,
    amount     NUMERIC(19, 2) NOT NULL,
    CONSTRAINT chk_entries_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT chk_entries_amount_positive CHECK (amount > 0),
    CONSTRAINT uq_entries_line UNIQUE (journal_id, line_no)
);

-- GET /api/v1/journals?accountId=... (an account's entries, newest first)
CREATE INDEX idx_entries_account ON journal_entries (account_id, id);
